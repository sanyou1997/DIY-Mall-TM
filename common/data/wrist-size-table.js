/**
 * 按身高体重查表估算手围（cm）。取最近档位，超出范围按边界档。
 */
export function estimateWristCm(heightCm, weightKg) {
	const nearestIdx = (arr, v) => {
		let best = 0, bestDiff = Infinity;
		for (let i = 0; i < arr.length; i++) {
			const d = Math.abs(arr[i] - v);
			if (d < bestDiff) { bestDiff = d; best = i; }
		}
		return best;
	};
	const hi = nearestIdx(WRIST_TABLE.heights, Number(heightCm) || 165);
	const wi = nearestIdx(WRIST_TABLE.weights, Number(weightKg) || 60);
	return WRIST_TABLE.data[hi][wi];
}
